const { chromium } = require('playwright-core')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1200 } })
  const failed = [], slow = []
  page.on('requestfailed', (r) => failed.push(r.url().slice(0, 160) + ' :: ' + (r.failure() ? r.failure().errorText : '?')))
  page.on('response', (r) => { if (r.status() >= 400) slow.push(r.status() + ' ' + r.url().slice(0, 160)) })
  page.on('console', (m) => { if (m.type() === 'error') failed.push('console: ' + m.text().slice(0, 160)) })

  await page.goto('https://roamly-ai-trip-planner.app.workbuddy.host/', { waitUntil: 'networkidle', timeout: 60000 })
  await page.waitForTimeout(2000)
  await page.getByPlaceholder('Enter a city').fill('Hangzhou, China')
  const pickers = page.locator('.n-date-picker input')
  await pickers.nth(0).click(); await page.keyboard.type('2026-10-05'); await page.keyboard.press('Enter')
  await page.waitForTimeout(400)
  await pickers.nth(1).click(); await page.keyboard.type('2026-10-07'); await page.keyboard.press('Enter')
  await page.waitForTimeout(600)
  await page.getByRole('button', { name: /START PLANNING/i }).last().click()

  await page.waitForTimeout(90000)
  console.log('结果页路径:', await page.evaluate(() => location.pathname))
  console.log('\n失败请求:')
  ;[...new Set(failed)].forEach((x) => console.log('  ' + x))
  console.log('\n非 2xx 响应:')
  ;[...new Set(slow)].forEach((x) => console.log('  ' + x))
  await page.screenshot({ path: '/tmp/final-result.png', fullPage: false })
  await browser.close()
})().catch((e) => { console.error('失败: ' + e.message); process.exit(1) })
